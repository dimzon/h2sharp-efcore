#nullable enable
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata;
using NodaTime;
using Xunit;
using H2Sharp.EntityFrameworkCore.TestUtilities;

namespace H2Sharp.EntityFrameworkCore;

/// <summary>
///     Checks the SQL the provider generates against the reference H2 engine.
/// </summary>
/// <remarks>
///     <para>
///         The port is still being filled in, and a provider test that runs against the port proves
///         only that the port agrees with itself. These tests run the generated SQL against the
///         reference engine instead, so they say something about H2 2.5 -- which is what the provider
///         has to work against.
///     </para>
///     <para>
///         They skip when the reference jar is not available. A missing reference is not a provider
///         defect, and a test that fails because the environment lacks a jar is worse than no test.
///     </para>
/// </remarks>
public class H2GeneratedSqlReferenceTest
{
    private class Blog
    {
        public int Id { get; set; }

        public string? Title { get; set; }

        public int Views { get; set; }

        public DateTime Created { get; set; }
    }

    private class Post
    {
        public int Id { get; set; }

        public string? Title { get; set; }

        public int BlogId { get; set; }
    }

    private class Entry
    {
        public int Id { get; set; }

        public LocalDate Day { get; set; }

        public LocalTime At { get; set; }

        public Instant Moment { get; set; }
    }

    private class BlogContext(string? connectionString = null) : DbContext
    {
        public DbSet<Blog> Blogs => Set<Blog>();

        public DbSet<Post> Posts => Set<Post>();

        protected override void OnConfiguring(DbContextOptionsBuilder optionsBuilder)
            => optionsBuilder.UseH2(connectionString ?? "jdbc:h2:mem:reference");

        protected override void OnModelCreating(ModelBuilder modelBuilder)
        {
            modelBuilder.Entity<Blog>().ToTable("Blogs");
            modelBuilder.Entity<Post>().ToTable("Posts");
        }
    }

    private class EntryContext : DbContext
    {
        public DbSet<Entry> Entries => Set<Entry>();

        protected override void OnConfiguring(DbContextOptionsBuilder optionsBuilder)
            => optionsBuilder.UseH2("jdbc:h2:mem:reference", o => o.UseNodaTime());

        protected override void OnModelCreating(ModelBuilder modelBuilder)
            => modelBuilder.Entity<Entry>().ToTable("Entries");
    }

    [Fact]
    public void The_generated_create_script_is_accepted_by_the_reference_engine()
    {
        Assert.True(H2ReferenceOracle.IsAvailable, "The reference H2 jar is not available; skipping.");

        using var context = new BlogContext();
        var script = context.Database.GenerateCreateScript();

        var (accepted, output) = H2ReferenceOracle.Run(script);

        Assert.True(accepted, $"The reference engine rejected the generated script:{Environment.NewLine}{output}{Environment.NewLine}{script}");
    }

    [Fact]
    public void The_generated_create_script_uses_H2_types()
    {
        using var context = new BlogContext();
        var script = context.Database.GenerateCreateScript();

        // The reference engine has no serial pseudo-type, no jsonb and no bytea: an auto-generated
        // column is an IDENTITY one, and the binary and character types are H2's own.
        Assert.Contains("GENERATED BY DEFAULT AS IDENTITY", script);
        Assert.DoesNotContain("serial", script);
        Assert.DoesNotContain("jsonb", script);
        Assert.DoesNotContain("bytea", script);
    }

    [Fact]
    public void The_generated_query_is_accepted_by_the_reference_engine()
    {
        Assert.True(H2ReferenceOracle.IsAvailable, "The reference H2 jar is not available; skipping.");

        using var context = new BlogContext();

        // A query, not a script: the table alias is written without the AS, and the reference
        // engine is asked whether it reads that. It does -- but the reference is the authority,
        // not the port.
        var query = context.Blogs.Select(b => new { b.Id, b.Title }).ToQueryString();

        Assert.Contains("\"Blogs\" \"b\"", query);
        Assert.DoesNotContain("AS", query);

        var script = $"""
            CREATE TABLE "Blogs" ("Id" integer NOT NULL, "Title" varchar(50), CONSTRAINT "PK_Blogs" PRIMARY KEY ("Id"));
            {query};
            """;

        var (accepted, output) = H2ReferenceOracle.Run(script);

        Assert.True(accepted, $"The reference engine rejected the generated query:{Environment.NewLine}{output}{Environment.NewLine}{script}");
    }

    [Fact]
    public void The_generated_create_script_for_the_NodaTime_plugin_is_accepted_by_the_reference_engine()
    {
        Assert.True(H2ReferenceOracle.IsAvailable, "The reference H2 jar is not available; skipping.");

        using var context = new EntryContext();
        var script = context.Database.GenerateCreateScript();

        var (accepted, output) = H2ReferenceOracle.Run(script);

        Assert.True(accepted, $"The reference engine rejected the generated script:{Environment.NewLine}{output}{Environment.NewLine}{script}");
    }
}
