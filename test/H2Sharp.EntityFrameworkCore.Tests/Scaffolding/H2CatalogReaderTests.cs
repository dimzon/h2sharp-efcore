using H2Sharp.Data;
using H2Sharp.EntityFrameworkCore.Scaffolding.Internal;
using Xunit;

namespace H2Sharp.EntityFrameworkCore.Scaffolding;

public class H2CatalogReaderTests
{
    [Fact]
    public void Tables_columns_keys_and_indexes_are_read_as_typed_rows()
    {
        using var connection = Open();
        Execute(
            connection,
            """
CREATE TABLE "ReaderItems" (
    "Id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Name" VARCHAR(20) NOT NULL,
    "Amount" NUMERIC(10, 2)
);
CREATE INDEX "ReaderItems_Name" ON "ReaderItems"("Name" DESC);
CREATE TABLE "ReaderNotes" (
    "Id" INTEGER PRIMARY KEY,
    "ItemId" INTEGER,
    CONSTRAINT "FK_ReaderNotes_Items" FOREIGN KEY ("ItemId") REFERENCES "ReaderItems"("Id")
);
""");

        IH2CatalogReader reader = new H2CatalogReader();

        Assert.True(reader.IsAvailable(connection));
        Assert.Contains("PUBLIC", reader.GetSchemas(connection));
        Assert.Contains(reader.GetTables(connection, "PUBLIC"), t => t.Name == "ReaderItems" && t.Type == "BASE TABLE");

        var columns = reader.GetColumns(connection, "PUBLIC");
        var id = Assert.Single(columns, c => c.TableName == "ReaderItems" && c.ColumnName == "Id");
        Assert.Equal("YES", id.IsIdentity);
        Assert.Equal("BY DEFAULT", id.IdentityGeneration);
        Assert.Equal("NO", id.IsNullable);

        var name = Assert.Single(columns, c => c.ColumnName == "Name");
        Assert.Equal("CHARACTER VARYING", name.DataType);
        Assert.Equal(20, name.CharacterMaximumLength);

        var amount = Assert.Single(columns, c => c.ColumnName == "Amount");
        Assert.Equal("NUMERIC", amount.DeclaredDataType);
        Assert.Equal(10, amount.DeclaredNumericPrecision);
        Assert.Equal(2, amount.DeclaredNumericScale);

        Assert.Contains(reader.GetKeys(connection, "PUBLIC"), k => k.ConstraintType == "PRIMARY KEY" && k.ColumnName == "Id");

        var index = Assert.Single(reader.GetIndexes(connection, "PUBLIC"), i => i.IndexName == "ReaderItems_Name");
        Assert.Equal("ReaderItems", index.TableName);
        Assert.Equal("Name", index.ColumnName);
        Assert.Equal("DESC", index.OrderingSpecification);

        var foreignKey = Assert.Single(reader.GetForeignKeys(connection), f => f.ConstraintName == "FK_ReaderNotes_Items");
        Assert.Equal("ReaderNotes", foreignKey.TableName);
        Assert.Equal("ItemId", foreignKey.ColumnName);
        Assert.NotNull(foreignKey.UniqueConstraintName);
        Assert.Equal(
            "ReaderItems",
            reader.GetPrincipalTableName(connection, foreignKey.UniqueConstraintSchema, foreignKey.UniqueConstraintName));
        Assert.Equal(
            ["Id"],
            reader.GetPrincipalColumns(connection, foreignKey.UniqueConstraintSchema, foreignKey.UniqueConstraintName));
    }

    [Fact]
    public void Sequences_and_enum_labels_are_read_with_their_facets()
    {
        using var connection = Open();
        Execute(
            connection,
            """
CREATE SEQUENCE "ReaderSeq" START WITH 5 INCREMENT BY 2;
CREATE TYPE "ReaderMood" AS ENUM ('HAPPY', 'SAD');
""");

        var reader = new H2CatalogReader();

        var sequence = Assert.Single(reader.GetSequences(connection, "PUBLIC"), s => s.Name == "ReaderSeq");
        Assert.Equal(5, sequence.StartValue);
        Assert.Equal(2, sequence.Increment);
        Assert.False(sequence.IsCyclic);

        Assert.Equal(
            ["HAPPY", "SAD"],
            reader.GetEnums(connection, "PUBLIC").Where(e => e.Name == "ReaderMood").Select(e => e.Value));
    }

    [Fact]
    public void Presence_queries_and_principal_lookup_come_from_the_same_catalog()
    {
        using var connection = Open();
        Execute(connection, "CREATE TABLE \"ReaderPrincipal\" (\"Id\" INTEGER PRIMARY KEY)");

        var reader = new H2CatalogReader();

        Assert.True(reader.HasTables(connection, "PUBLIC"));
        Assert.True(reader.SchemaExists(connection, "PUBLIC"));
        Assert.False(reader.SchemaExists(connection, "NO_SUCH_SCHEMA"));

        var primaryKey = Assert.Single(reader.GetKeys(connection, "PUBLIC"));
        Assert.Equal("ReaderPrincipal", reader.GetPrincipalTableName(connection, "PUBLIC", primaryKey.ConstraintName));
        Assert.Equal(["Id"], reader.GetPrincipalColumns(connection, "PUBLIC", primaryKey.ConstraintName));
    }

    private static H2Connection Open()
    {
        var connection = new H2Connection(
            "Data Source=catalog_reader_" + Guid.NewGuid().ToString("N") + ";Storage=Memory");
        connection.Open();
        return connection;
    }

    private static void Execute(H2Connection connection, string sql)
    {
        using var command = connection.CreateCommand();
        command.CommandText = sql;
        command.ExecuteNonQuery();
    }
}
