using H2Sharp.EntityFrameworkCore.TestUtilities;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Migrations;
using Microsoft.EntityFrameworkCore.Migrations.Operations;
using H2Sharp.EntityFrameworkCore.Metadata;
using H2Sharp.EntityFrameworkCore.Metadata.Internal;

namespace H2Sharp.EntityFrameworkCore;

public class H2IdentitySeedTests
{
    [Fact]
    public void Legacy_serial_creates_h2_identity_and_changes_generation_mode()
    {
        using var connection = new H2Connection("jdbc:h2:mem:legacy_identity");
        using var context = new AscendingContext(new DbContextOptionsBuilder<AscendingContext>().UseH2(connection).Options);
        var generator = context.GetService<IMigrationsSqlGenerator>();
        var create = new CreateTableOperation { Name = "Legacy" };
        create.Columns.Add(new AddColumnOperation
        {
            Name = "Id", Table = "Legacy", ClrType = typeof(int), ColumnType = "integer",
            [H2AnnotationNames.ValueGenerationStrategy] = H2ValueGenerationStrategy.SerialColumn
        });
        var change = new AlterColumnOperation
        {
            Name = "Id", Table = "Legacy", ClrType = typeof(int), ColumnType = "integer",
            [H2AnnotationNames.ValueGenerationStrategy] = H2ValueGenerationStrategy.IdentityAlwaysColumn,
            OldColumn = new AddColumnOperation
            {
                Name = "Id", Table = "Legacy", ClrType = typeof(int), ColumnType = "integer",
                [H2AnnotationNames.ValueGenerationStrategy] = H2ValueGenerationStrategy.SerialColumn
            }
        };
        var ddl = string.Concat(generator.Generate([create, change]).Select(c => c.CommandText));
        Assert.Contains("GENERATED BY DEFAULT AS IDENTITY", ddl, StringComparison.Ordinal);
        Assert.Contains("SET GENERATED ALWAYS", ddl, StringComparison.Ordinal);
        Assert.DoesNotContain("setval", ddl, StringComparison.OrdinalIgnoreCase);
        Assert.DoesNotContain("OWNED BY", ddl, StringComparison.Ordinal);
        if (H2ReferenceOracle.IsAvailable)
        {
            var reference = H2ReferenceOracle.Run($"""
                {ddl}
                INSERT INTO "Legacy" DEFAULT VALUES;
                SELECT 1 / CASE WHEN MIN("Id") = 1 THEN 1 ELSE 0 END FROM "Legacy";
                """);
            Assert.True(reference.Accepted, reference.Output);
        }
    }

    [Theory]
    [InlineData(false, false)]
    [InlineData(false, true)]
    [InlineData(true, false)]
    [InlineData(true, true)]
    public void Seeded_identity_is_restarted_with_h2_ddl(bool descending, bool idempotent)
    {
        using var connection = new H2Connection("jdbc:h2:mem:identity_seed_" + Guid.NewGuid().ToString("N"));
        using var context = descending
            ? new DescendingContext(new DbContextOptionsBuilder<DescendingContext>().UseH2(connection).Options)
            : (DbContext)new AscendingContext(new DbContextOptionsBuilder<AscendingContext>().UseH2(connection).Options);
        var model = context.GetService<IDesignTimeModel>().Model;
        var seed = descending ? -8 : 100;
        var sql = string.Concat(context.GetService<IMigrationsSqlGenerator>().Generate(
            [new InsertDataOperation { Table = "Seeds", Columns = ["Id"], Values = new object[,] { { seed } } }],
            model,
            idempotent ? MigrationsSqlGenerationOptions.Idempotent : MigrationsSqlGenerationOptions.Default)
            .Select(c => c.CommandText));

        Assert.Contains("RESTART WITH", sql, StringComparison.Ordinal);
        Assert.DoesNotContain("setval", sql, StringComparison.OrdinalIgnoreCase);
        Assert.DoesNotContain("pg_get_serial_sequence", sql, StringComparison.OrdinalIgnoreCase);
        Assert.DoesNotContain("PERFORM", sql, StringComparison.Ordinal);

        if (H2ReferenceOracle.IsAvailable)
        {
            var next = descending ? -10 : 101;
            var reference = H2ReferenceOracle.Run($"""
                {context.Database.GenerateCreateScript()}
                {sql}
                INSERT INTO "Seeds" DEFAULT VALUES;
                SELECT 1 / CASE WHEN COUNT(*) = 1 THEN 1 ELSE 0 END FROM "Seeds" WHERE "Id" = {next};
                """);
            Assert.True(reference.Accepted, reference.Output);

            // Seeding values behind the current identity must not move it backwards.
            var advanced = descending ? -50 : 500;
            reference = H2ReferenceOracle.Run($"""
                {context.Database.GenerateCreateScript()}
                ALTER TABLE "Seeds" ALTER COLUMN "Id" RESTART WITH {advanced};
                {sql}
                INSERT INTO "Seeds" DEFAULT VALUES;
                SELECT 1 / CASE WHEN COUNT(*) = 1 THEN 1 ELSE 0 END FROM "Seeds" WHERE "Id" = {advanced};
                """);
            Assert.True(reference.Accepted, reference.Output);
        }
    }

    [Fact]
    public void Adding_identity_to_a_column_keeps_its_options()
    {
        using var connection = new H2Connection("jdbc:h2:mem:add_identity_options");
        using var context = new AscendingContext(new DbContextOptionsBuilder<AscendingContext>().UseH2(connection).Options);
        var change = new AlterColumnOperation
        {
            Name = "Id", Table = "Plain", ClrType = typeof(int), ColumnType = "integer",
            [H2AnnotationNames.ValueGenerationStrategy] = H2ValueGenerationStrategy.IdentityByDefaultColumn,
            [H2AnnotationNames.IdentityOptions] = new IdentitySequenceOptionsData { StartValue = 100, IncrementBy = 2 }.Serialize(),
            OldColumn = new AddColumnOperation { Name = "Id", Table = "Plain", ClrType = typeof(int), ColumnType = "integer" }
        };
        var ddl = string.Concat(context.GetService<IMigrationsSqlGenerator>().Generate([change]).Select(c => c.CommandText));
        Assert.Contains("RESTART WITH 100", ddl, StringComparison.Ordinal);
        Assert.Contains("SET INCREMENT BY 2", ddl, StringComparison.Ordinal);
        if (H2ReferenceOracle.IsAvailable)
        {
            var reference = H2ReferenceOracle.Run($"""
                CREATE TABLE "Plain" ("Id" INTEGER NOT NULL);
                {ddl}
                INSERT INTO "Plain" DEFAULT VALUES;
                INSERT INTO "Plain" DEFAULT VALUES;
                SELECT 1 / CASE WHEN MIN("Id") = 100 AND MAX("Id") = 102 THEN 1 ELSE 0 END FROM "Plain";
                """);
            Assert.True(reference.Accepted, reference.Output);
        }
    }

    private sealed class Seed
    {
        public int Id { get; set; }
    }

    private sealed class AscendingContext(DbContextOptions<AscendingContext> options) : DbContext(options)
    {
        protected override void OnModelCreating(ModelBuilder modelBuilder)
        {
            modelBuilder.Entity<Seed>().ToTable("Seeds");
            modelBuilder.Entity<Seed>().Property(s => s.Id).UseIdentityByDefaultColumn();
        }
    }

    private sealed class DescendingContext(DbContextOptions<DescendingContext> options) : DbContext(options)
    {
        protected override void OnModelCreating(ModelBuilder modelBuilder)
        {
            modelBuilder.Entity<Seed>().ToTable("Seeds");
            modelBuilder.Entity<Seed>().Property(s => s.Id).UseIdentityByDefaultColumn()
                .HasIdentityOptions(startValue: -1, incrementBy: -2);
        }
    }
}
