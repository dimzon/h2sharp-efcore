namespace H2Sharp.EntityFrameworkCore.Metadata;

/// <summary>
///     Defines strategies to use when generating values for database columns.
/// </summary>
/// <remarks>
///     See <see href="https://aka.ms/efcore-docs-conventions">Model building conventions</see>.
/// </remarks>
public enum H2ValueGenerationStrategy
{
    /// <summary>
    ///     No H2-specific strategy.
    /// </summary>
    None,

    /// <summary>
    ///     <para>
    ///         A sequence-based hi-lo pattern where blocks of IDs are allocated from the server and
    ///         used client-side for generating keys.
    ///     </para>
    ///     <para>
    ///         This is an advanced pattern--only use this strategy if you are certain it is what you need.
    ///     </para>
    /// </summary>
    SequenceHiLo,

    /// <summary>
    ///     <para>
    ///         The legacy serial column strategy, kept so that a model written for PostgreSQL keeps
    ///         working. H2 has no serial pseudo-type: the column is written as
    ///         <c>GENERATED BY DEFAULT AS IDENTITY</c>, exactly as <see cref="IdentityByDefaultColumn" /> does.
    ///     </para>
    ///     <para>
    ///         Prefer <see cref="IdentityByDefaultColumn" /> in new projects: it is the same column under
    ///         the name H2 2.5 actually has for it.
    ///     </para>
    /// </summary>
    SerialColumn,

    /// <summary>
    ///     <para>Selects the always-identity column strategy (<c>GENERATED ALWAYS AS IDENTITY</c>: a value cannot be provided).</para>
    /// </summary>
    IdentityAlwaysColumn,

    /// <summary>
    ///     <para>Selects the by-default-identity column strategy (<c>GENERATED BY DEFAULT AS IDENTITY</c>: a value can be provided to override the identity mechanism).</para>
    /// </summary>
    IdentityByDefaultColumn,

    /// <summary>
    ///     A pattern that uses a database sequence to generate values for the column.
    /// </summary>
    Sequence
}

/// <summary>
///     Extension methods over <see cref="H2ValueGenerationStrategy" />.
/// </summary>
public static class H2ValueGenerationStrategyExtensions
{
    /// <summary>
    ///     Whether the given strategy is one that makes the database generate the value.
    /// </summary>
    /// <remarks>
    ///     <para>
    ///         SerialColumn counts as identity here. Upstream it meant "use the serial pseudo-type",
    ///         which PostgreSQL has and H2 does not; in H2 the only auto-generated column is an IDENTITY
    ///         one, and GENERATED BY DEFAULT is the closest thing to serial -- it is the variant that
    ///         still accepts a value when one is supplied. Treating it as anything else would emit SQL
    ///         that H2 cannot parse, and would leave the column without a generator.
    ///     </para>
    /// </remarks>
    public static bool IsIdentity(this H2ValueGenerationStrategy strategy)
        => strategy is H2ValueGenerationStrategy.SerialColumn
            or H2ValueGenerationStrategy.IdentityByDefaultColumn
            or H2ValueGenerationStrategy.IdentityAlwaysColumn;

    /// <summary>
    ///     Whether the given strategy is one that makes the database generate the value.
    /// </summary>
    public static bool IsIdentity(this H2ValueGenerationStrategy? strategy)
        => strategy is H2ValueGenerationStrategy.SerialColumn
            or H2ValueGenerationStrategy.IdentityByDefaultColumn
            or H2ValueGenerationStrategy.IdentityAlwaysColumn;
}
