    {
        var path = (H2Path)value;
        var sb = new StringBuilder();
        sb.Append("PATH '");
        sb.Append(path.Open ? '[' : '(');
        for (var i = 0; i < path.Count; i++)
        {
            sb.Append('(');
            sb.Append(path[i].X.ToString("G17", CultureInfo.InvariantCulture));
            sb.Append(',');
            sb.Append(path[i].Y.ToString("G17", CultureInfo.InvariantCulture));
            sb.Append(')');
            if (i < path.Count - 1)
            {
                sb.Append(',');
            }
        }

        sb.Append(path.Open ? ']' : ')');
        sb.Append('\'');
        return sb.ToString();
