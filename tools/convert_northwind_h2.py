"""One-time conversion of the Npgsql Northwind dump into an H2 test-store script.

The source file is a PostgreSQL/SQL Server hybrid dump: SET commands, CREATE EXTENSION, GO batch
separators, N'...' string literals and E'\\\\x...' bytea literals. H2 needs plain DDL with its own
type names and X'...' binary literals. This script is kept so the conversion is reproducible.
"""
import re
import sys
from pathlib import Path

SOURCE = Path('test/H2Sharp.EntityFrameworkCore.FunctionalTests/Northwind.sql')
TARGET = Path('test/H2Sharp.EntityFrameworkCore.FunctionalTests/NorthwindH2.sql')


def convert_table(sql: str) -> str:
    # SQL Server names DEFAULT constraints; H2 writes the default inline.
    sql = re.sub(
        r'CONSTRAINT\s+"DF_[^"]+"\s+DEFAULT\s+\(([^)]*)\)',
        lambda m: 'DEFAULT FALSE' if m.group(1).lower() == 'false' else 'DEFAULT ' + m.group(1),
        sql,
        flags=re.I)
    sql = re.sub(r'"varchar"\s*\(\s*(\d+)\s*\)', r'VARCHAR(\1)', sql, flags=re.I)
    sql = re.sub(r'\bSERIAL\b', 'INTEGER GENERATED BY DEFAULT AS IDENTITY', sql, flags=re.I)
    sql = re.sub(r'\bnchar\s*\(\s*(\d+)\s*\)', r'CHAR(\1)', sql, flags=re.I)
    sql = re.sub(r'\bvarchar\s*\(\s*(\d+)\s*\)', r'VARCHAR(\1)', sql, flags=re.I)
    sql = re.sub(r'\bbytea\b', 'VARBINARY', sql, flags=re.I)
    sql = re.sub(r'\btext\b', 'VARCHAR', sql, flags=re.I)
    sql = re.sub(r'\bmoney\b', 'DECIMAL(19,4)', sql, flags=re.I)
    sql = re.sub(r'\bbool\b', 'BOOLEAN', sql, flags=re.I)
    sql = re.sub(r'\bnumeric\b', 'DECIMAL', sql, flags=re.I)
    sql = re.sub(r'\btimestamp\b', 'TIMESTAMP', sql, flags=re.I)
    sql = re.sub(r'\bint\b', 'INTEGER', sql, flags=re.I)
    return sql


def convert_insert(sql: str) -> str:
    sql = re.sub(r"\bN'", "'", sql)
    sql = re.sub(r"E'\\\\x([0-9A-Fa-f]+)'", r"X'\1'", sql)
    sql = sql.replace('::numeric', '').replace('::INT', '')
    return sql


def main() -> int:
    text = SOURCE.read_text(encoding='utf-8', errors='replace').replace('\r\n', '\n')
    batches = [b.strip() for b in re.split(r'(?mi)^\s*go\s*$', text) if b.strip()]

    output = [
        '-- Generated from Northwind.sql by tools/convert_northwind_h2.py. Do not edit by hand.',
    ]
    skipped = []
    for batch in batches:
        # A batch may mix PG-only commands with a table definition; drop only the commands.
        lines = [
            line for line in batch.split('\n')
            if not line.strip().upper().startswith(('SET ', 'CREATE EXTENSION', '--', '/*'))
            and 'TRIGGER ALL' not in line.upper()
        ]
        batch = '\n'.join(lines).strip()
        if not batch:
            continue
        upper = batch.upper()
        if upper.startswith(('CREATE INDEX', 'CREATE FUNCTION')) or (
                upper.startswith('ALTER TABLE') and 'ADD CONSTRAINT "FK_' in upper):
            # The dump disables triggers while loading rows; H2 cannot. Foreign keys are added
            # back nowhere: the EF model carries the relationships the tests need.
            skipped.append(upper.split()[0])
            continue
        if upper.startswith('CREATE TABLE'):
            batch = convert_table(batch)
            batch = re.sub(
                r',\s*CONSTRAINT\s+"FK_[^"]+"\s+FOREIGN KEY\s*\([^)]*\)\s*REFERENCES\s+"[^"]+"\s*\([^)]*\)',
                '',
                batch,
                flags=re.I | re.S)
        elif upper.startswith('INSERT INTO'):
            batch = convert_insert(batch)
        output.append(batch.rstrip(';') + ';')

    TARGET.write_text('\n\n'.join(output) + '\n', encoding='utf-8')
    print(f'wrote {TARGET} ({len(output) - 1} statements, skipped {len(skipped)})')
    return 0


if __name__ == '__main__':
    sys.exit(main())
